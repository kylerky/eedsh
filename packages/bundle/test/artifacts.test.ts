import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterAll, describe, expect, it } from 'vitest'
import { checkBundlePatch, defineBundlePatch, writeBundlePatch } from '../src/index'

const directory = mkdtempSync(join(tmpdir(), 'eedsh-bundle-artifacts-'))

afterAll(() => {
  rmSync(directory, { recursive: true, force: true })
})

const patch = defineBundlePatch((builder) => {
  builder.insert({ id: 'plugin', name: 'plugin', config: { enabled: true } })
})

describe('bundle patch artifacts', () => {
  it('writes the exact emission and checks it without changing the file', () => {
    const path = join(directory, 'nested', 'cordis.patch.yml')
    writeBundlePatch(patch, path)
    const written = readFileSync(path, 'utf8')
    expect(written).toContain('Generated by @eedsh/bundle')
    const result = checkBundlePatch(patch, path)
    expect(result.ok).toBe(true)
    expect(readFileSync(path, 'utf8')).toBe(written)
  })

  it('reports a missing artifact without writing it', () => {
    const path = join(directory, 'missing.yml')
    const result = checkBundlePatch(patch, path)
    expect(result.ok).toBe(false)
    expect(result.message).toMatch(/does not exist/)
    expect(() => readFileSync(path, 'utf8')).toThrow()
  })

  it('reports a stale artifact and leaves its bytes unchanged', () => {
    const path = join(directory, 'stale.yml')
    writeBundlePatch(patch, path)
    const before = readFileSync(path, 'utf8')
    const changed = defineBundlePatch((builder) => {
      builder.insert({ id: 'different', name: 'different' })
    })
    const result = checkBundlePatch(changed, path)
    expect(result.ok).toBe(false)
    expect(result.message).toMatch(/stale/)
    expect(readFileSync(path, 'utf8')).toBe(before)
  })
})
